package com.playlist.playlistmanage.model;

import jakarta.persistence.*;

@Entity
@Table(name = "Playlist")
public class PlaylistModel{

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private int pid;

    private String name;       // e.g. "My Playlist", "Happy Vibes"
    private String mood;       // auto-generated mood filter
    private String genre;      // auto-generated genre filter
    private boolean isAutoGenerated;

    // --- Getters and Setters ---

    public int getPid() {
        return pid;
    }

    public void setPid(int pid) {
        this.pid = pid;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getMood() {
        return mood;
    }

    public void setMood(String mood) {
        this.mood = mood;
    }

    public String getGenre() {
        return genre;
    }

    public void setGenre(String genre) {
        this.genre = genre;
    }

    public boolean isAutoGenerated() {
        return isAutoGenerated;
    }

    public void setAutoGenerated(boolean autoGenerated) {
        isAutoGenerated = autoGenerated;
    }

    public PlaylistModel() {}

    public PlaylistModel(int pid, String name, String mood, String genre, boolean isAutoGenerated) {
        this.pid = pid;
        this.name = name;
        this.mood = mood;
        this.genre = genre;
        this.isAutoGenerated = isAutoGenerated;
    }
}
